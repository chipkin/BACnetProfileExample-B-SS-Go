// -----------------------------------------------------------------------------
// 1. Example configuration
// -----------------------------------------------------------------------------
const appName = "BACnet B-SS (Smart Sensor) Example - Go"
const appVersion = "1.1.0"

// The device instance. BACnet requires this to be configurable, so it
// defaults to 389001 and can be overridden with --deviceID.
const defaultDeviceInstance uint32 = 389001

// -----------------------------------------------------------------------------
// 2. The sensor Simulation (NOT part of the BACnet Surface)
//
// Stands in for the physical world. Once a second:
//   - Analog Input 1 moves 0.5 C, ramping up to 26.0 and back down to 18.0
//   - Binary Input 1 toggles every 3 s
//   - Multi-State Input 1 steps 1 -> 2 -> 3 -> 1 every 4 s
//
// and the sensor wire is checked.
//
// The broken wire is a TEST-ONLY hook, not a feature: when the environment
// variable named by sensorFaultFileVariable names a file, the wire counts as
// broken for as long as that file exists. A Wire Test creates and deletes the
// file to break and repair the sensor. While the wire is broken the reading
// freezes at its last good value (a dead wire measures nothing new) and
// Reliability reads OPEN_LOOP; once the file is gone the reading resumes and
// Reliability returns to NO_FAULT_DETECTED. On a real device, set Reliability
// from your hardware's own diagnostics.
// -----------------------------------------------------------------------------
const sensorFaultFileVariable = "CAS_EXAMPLE_TEST_SENSOR_FAULT_FILE"

const (
	analogInputLowest          float32 = 18.0
	analogInputHighest         float32 = 26.0
	analogInputStep            float32 = 0.5
	binaryInputToggleSeconds           = 3
	multiStateInputStepSeconds         = 4
)

var sensorFaultFile string // read once at start-up; empty = no hook
var simulationStarted time.Time
var simulationLastSecond int64
var analogInputDirection float32 = 1.0

func sensorWireBroken() bool {
	if sensorFaultFile == "" {
		return false
	}
	_, err := os.Stat(sensorFaultFile)
	return err == nil
}

func sensorSimulationTick() {
	secondsRunning := int64(time.Since(simulationStarted) / time.Second)
	if secondsRunning == simulationLastSecond {
		return
	}
	simulationLastSecond = secondsRunning

	reliability := common.ReliabilityNoFaultDetected
	if sensorWireBroken() {
		reliability = common.ReliabilityOpenLoop
	}
	common.WithState(func(state *common.DeviceState) {
		if reliability != state.AnalogInput1Reliability {
			state.AnalogInput1Reliability = reliability
			if reliability == common.ReliabilityOpenLoop {
				fmt.Println("Simulation: Analog Input 1 (Bronze) sensor wire broken - Reliability OPEN_LOOP")
			} else {
				fmt.Println("Simulation: Analog Input 1 (Bronze) sensor wire repaired - Reliability NO_FAULT_DETECTED")
			}
		}
		if state.AnalogInput1Reliability == common.ReliabilityNoFaultDetected {
			if state.AnalogInput1Value >= analogInputHighest {
				analogInputDirection = -1.0
			} else if state.AnalogInput1Value <= analogInputLowest {
				analogInputDirection = 1.0
			}
			state.AnalogInput1Value += analogInputDirection * analogInputStep
		}
		if secondsRunning%binaryInputToggleSeconds == 0 {
			state.BinaryInput1Value = 1 - state.BinaryInput1Value
		}
		if secondsRunning%multiStateInputStepSeconds == 0 {
			state.MultiStateInput1Value = state.MultiStateInput1Value%common.MultiStateInputNumberOfStates + 1
		}
	})
}

// -----------------------------------------------------------------------------
// 3. Property "get" callbacks - see property_dispatch.go
// -----------------------------------------------------------------------------
// getPropertyReal, getPropertyEnumerated, getPropertyUnsignedInteger,
// getPropertyBool, getPropertyOctetString and getPropertyCharString, with the
// long note on the errorCode out-parameter and on what a declining callback
// really does. Registered with the stack in main() below.

// -----------------------------------------------------------------------------
// Interactive commands
// -----------------------------------------------------------------------------
// The C++ edition reads single raw key presses (_kbhit()/_getch(), or a raw
// POSIX terminal), including the arrow keys. Go's standard library has no
// portable raw-keyboard read, so this edition reads stdin byte by byte in
// the terminal's normal (line) mode: type a key and press Enter. 'u' and 'd'
// stand in for the up/down arrows. A 'q' written to a pipe (the Wire Tests
// stop the example that way) quits at once, no Enter needed. A background
// goroutine blocks on the read and hands each command to the main loop over a
// channel; it never calls the stack.

type command int

const (
	commandHelp command = iota
	commandQuit
	commandUp
	commandDown
)

func spawnCommandReader() <-chan command {
	commands := make(chan command, 8)
	go func() {
		input := bufio.NewReader(os.Stdin)
		for {
			key, err := input.ReadByte()
			if err != nil {
				return // stdin closed: no more commands (Ctrl+C still quits)
			}
			switch key {
			case 'h', 'H':
				commands <- commandHelp
			case 'q', 'Q':
				commands <- commandQuit
			case 'u', 'U':
				commands <- commandUp
			case 'd', 'D':
				commands <- commandDown
			}
		}
	}()
	return commands
}

