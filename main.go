// 4. main()
// -----------------------------------------------------------------------------

// printMissingStackLibrary prints the series' message for a missing CAS
// BACnet Stack library (the same text in every language port) to stderr.
func printMissingStackLibrary(fileName string, searchedFolders []string) {
	lookedIn := "(the executable's folder could not be found)"
	if len(searchedFolders) > 0 {
		lookedIn = strings.Join(searchedFolders, "\n                ")
	}
	fmt.Fprintf(os.Stderr, `ERROR: This example cannot run without the CAS BACnet Stack library.

  Missing file: %s
  Looked in:    %s

The CAS BACnet Stack is a commercially licensed (paid) library from Chipkin.
It is not included in this release, so the example cannot start without it.

  - To license the CAS BACnet Stack: https://store.chipkin.com/contact-us
  - Licensed customers: build the library from the cas-bacnet-stack submodule
    (see README.md) and place %s next to this executable.
`, fileName, lookedIn, fileName)
}

func fail(format string, arguments ...interface{}) int {
	fmt.Printf("Error: "+format+"\n", arguments...)
	return 1
}

func run() int {
	// --- Load the CAS BACnet Stack -----------------------------------------------
	// The stack is a separately licensed library that a release of this example
	// does not include. It is loaded at run time (cgobridge, through the stack's
	// own adapter in DLL mode - LoadBACnetFunctions() in the C++ edition), from
	// the folder that holds this executable or, in a development checkout, from
	// submodules/cas-bacnet-stack/bin/. No other BACnetStack_* call may come
	// before it. --help and --version still work without it.
	arguments := os.Args[1:]
	stackFolder, searchedFolders := cgobridge.FindStackLibrary()
	stackVersion := "not loaded (library not found)"
	var loadError error
	if stackFolder != "" {
		if loadError = cgobridge.LoadStack(stackFolder); loadError == nil {
			stackVersion = cgobridge.StackVersion()
		} else {
			stackVersion = "not loaded (" + loadError.Error() + ")"
		}
	}

	// --- Command line + version --------------------------------------------------
	// --help / --version print and exit, so handle them before we bind a socket.
	if common.HandleHelpAndVersionArgs(arguments, appName, appVersion, stackVersion) {
		return 0
	}
	if stackFolder == "" {
		printMissingStackLibrary(cgobridge.StackLibraryFileName(), searchedFolders)
		return 1
	}
	if loadError != nil {
		fmt.Fprintf(os.Stderr, "Error: failed to load the CAS BACnet Stack from %s: %v\n", stackFolder, loadError)
		return 1
	}

	// Application_Software_Version (12) is this example's own version, and
	// Firmware_Revision (44) is the CAS BACnet Stack's - both computed once
	// here, so they can never drift from what --version prints.
	common.ApplicationSoftwareVersion = appVersion
	common.FirmwareRevision = stackVersion

	port := common.ParsePortArg(arguments, 47808)
	deviceInstance := common.ParseDeviceIDArg(arguments, defaultDeviceInstance)
	common.PrintVersion(appName, appVersion, stackVersion)
	common.WithState(func(state *common.DeviceState) { state.DeviceInstance = deviceInstance })

	// --- Bind the BACnet/IP socket -----------------------------------------------
	// Tell the transport which Network Port object owns the socket. The stack
	// identifies a link by its Network Port INSTANCE, so the transport
	// callbacks (and the start-up I-Am) have to name the one added below.
	cgobridge.SetNetworkPortInstance(common.NetworkPortInstance)
	if !cgobridge.SetupUDP(port) {
		return 1
	}

	// Capture the BACnet/IP addressing the Network Port object will report.
	local := common.GetLocalIPv4()
	if !local.Found {
		fmt.Println("FYI: could not read a local IPv4 address; Network Port IP_Address will report 0.0.0.0.")
	}
	common.WithState(func(state *common.DeviceState) {
		state.BacnetIPUDPPort = port
		state.IPAddress = local.Address
		state.IPSubnetMask = local.Netmask
	})

	// --- Register callbacks ------------------------------------------------------
	// The transport + time callbacks are shared boilerplate.
	cgobridge.RegisterCommonCallbacks()
	// The property callbacks are specific to this example (section 3).
	cgobridge.RegisterCallbackGetPropertyReal(getPropertyReal)
	cgobridge.RegisterCallbackGetPropertyEnumerated(getPropertyEnumerated)
	cgobridge.RegisterCallbackGetPropertyUnsignedInteger(getPropertyUnsignedInteger)
	cgobridge.RegisterCallbackGetPropertyCharacterString(getPropertyCharString)
	cgobridge.RegisterCallbackGetPropertyBool(getPropertyBool)
	cgobridge.RegisterCallbackGetPropertyOctetString(getPropertyOctetString)

	// --- Create the device -------------------------------------------------------
	if !cgobridge.AddDevice(deviceInstance) {
		return fail("Failed to add the Device %d.", deviceInstance)
	}

	// Enable ReadProperty (DS-RP-B) - the one mandatory service for B-SS.
	// We set it explicitly to make the profile requirement obvious.
	//
	// We deliberately do NOT enable WriteProperty, ReadPropertyMultiple,
	// SubscribeCOV, or any alarm/event service: a Smart Sensor does not
	// require them, so a faithful B-SS example leaves them off.
	if !cgobridge.SetServiceEnabled(deviceInstance, common.ServiceReadProperty, true) {
		return fail("Failed to enable the ReadProperty service.")
	}

	// Discovery: Who-Is/I-Am (DM-DDB-B) and Who-Has/I-Have (DM-DOB-B).
	//
	// These need enabling even though the device already ANSWERS them. The
	// stack's service defaults are whoIs + whoHas + readProperty only - iAm
	// and iHave are left FALSE. Who-Is is answered and the start-up I-Am is
	// sent regardless, but Protocol_Services_Supported is emitted verbatim
	// from that bitstring, so without these calls the device DOES I-Am and
	// I-Have while telling every client it supports neither.
	if !cgobridge.SetServiceEnabled(deviceInstance, common.ServiceWhoIs, true) ||
		!cgobridge.SetServiceEnabled(deviceInstance, common.ServiceIAm, true) ||
		!cgobridge.SetServiceEnabled(deviceInstance, common.ServiceWhoHas, true) ||
		!cgobridge.SetServiceEnabled(deviceInstance, common.ServiceIHave, true) {
		return fail("Failed to enable the discovery services (Who-Is/I-Am, Who-Has/I-Have).")
	}

	// --- Add the read-only sensor objects ----------------------------------------
	// Every stack setup call returns a bool; a real device should always check
	// it, so this example does too.
	if !cgobridge.AddObject(deviceInstance, common.ObjectTypeAnalogInput, common.AnalogInputInstance) {
		return fail("Failed to add Analog Input %d (Bronze).", common.AnalogInputInstance)
	}
	if !cgobridge.AddObject(deviceInstance, common.ObjectTypeBinaryInput, common.BinaryInputInstance) {
		return fail("Failed to add Binary Input %d (Emerald).", common.BinaryInputInstance)
	}
	if !cgobridge.AddObject(deviceInstance, common.ObjectTypeMultiStateInput, common.MultiStateInputInstance) {
		return fail("Failed to add Multi-State Input %d (Hot Pink).", common.MultiStateInputInstance)
	}

	// --- Add the Network Port object ---------------------------------------------
	// Every BACnet device (Protocol_Revision 17+) must have at least one
	// Network Port object describing the port it talks on. This one is the
	// BACnet/IP application port; it is the lowest layer, so its reference
	// port is "none". networkNumber 0 with quality "unknown" describes a local
	// port that has not learned its network number.
	if !cgobridge.AddNetworkPortObject(
		deviceInstance,
		common.NetworkPortInstance,
		common.NetworkPortNetworkTypeIPV4,
		common.NetworkPortProtocolLevelBACnetApplication,
		0, // networkNumber: not configured
		common.NetworkNumberQualityUnknown,
		common.NetworkPortReferencePortNone,
	) {
		return fail("Failed to add Network Port 1 (Vermilion).")
	}

	// --- Enable the OPTIONAL properties we choose to expose ----------------------
	// The stack enables an object's REQUIRED properties when the object is
	// added; only OPTIONAL ones need SetPropertyEnabled. Serving an optional
	// property from a Get callback is NOT enough: the stack checks
	// IsPropertyEnabled BEFORE it ever reaches the callbacks, so without the
	// enable the client reads back Error: unknown-property.
	if !cgobridge.SetPropertyEnabled(deviceInstance, common.ObjectTypeDevice, deviceInstance, common.PropertyIdentifierDescription, true) {
		return fail("Failed to enable Description on the Device object.")
	}
	if !cgobridge.SetPropertyEnabled(deviceInstance, common.ObjectTypeMultiStateInput, common.MultiStateInputInstance, common.PropertyIdentifierStateText, true) {
		return fail("Failed to enable State_Text on Multi-State Input 1 (Hot Pink).")
	}
	// Reliability is optional on an Analog Input; it is how a sensor says its
	// reading cannot be trusted. Enabling it also gives the FAULT bit of
	// Status_Flags its meaning - the stack derives that bit from it.
	if !cgobridge.SetPropertyEnabled(deviceInstance, common.ObjectTypeAnalogInput, common.AnalogInputInstance, common.PropertyIdentifierReliability, true) {
		return fail("Failed to enable Reliability on Analog Input 1 (Bronze).")
	}

	// The Simulation's test-only broken-wire hook (section 2).
	sensorFaultFile = os.Getenv(sensorFaultFileVariable)
	simulationStarted = time.Now()

	// Who-Is is answered automatically. The spec also requires a device to
	// announce itself on start-up, so broadcast an unsolicited I-Am now (to
	// the local subnet broadcast - the Network Port's own network).
	cgobridge.SendIAm(deviceInstance)

	fmt.Printf("FYI: Device %d (\"%s\") ready. Vendor ID %d. Press 'h' then Enter for help.\n",
		deviceInstance, common.DeviceName, common.VendorIdentifier)

	// Ctrl+C quits cleanly too.
	var running int32 = 1
	signals := make(chan os.Signal, 1)
	signal.Notify(signals, os.Interrupt, syscall.SIGTERM)
	go func() {
		<-signals
		atomic.StoreInt32(&running, 0)
	}()
	commands := spawnCommandReader()

	// --- Run the stack -----------------------------------------------------------
	// BACnetStack_Tick() processes incoming messages and timers. Call it
	// continuously, step the sensor Simulation beside it, and act on any
	// interactive command. Everything that touches the stack happens on this
	// one loop.
	for atomic.LoadInt32(&running) != 0 {
		cgobridge.Tick()
		sensorSimulationTick()

		select {
		case received := <-commands:
			switch received {
			case commandHelp:
				common.PrintHelp(appName, appVersion, stackVersion)
			case commandQuit:
				atomic.StoreInt32(&running, 0)
			case commandUp:
				common.WithState(func(state *common.DeviceState) {
					state.AnalogInput1Value += 1.1
					fmt.Printf("Analog Input 1 (Bronze) = %.1f C\n", state.AnalogInput1Value)
				})
			case commandDown:
				common.WithState(func(state *common.DeviceState) {
					state.AnalogInput1Value -= 1.1
					fmt.Printf("Analog Input 1 (Bronze) = %.1f C\n", state.AnalogInput1Value)
				})
			}
		default: // nothing typed this tick
		}

		time.Sleep(1 * time.Millisecond) // be a good citizen, don't spin the CPU
	}

	cgobridge.ShutdownUDP()
	return 0
}

func main() {
	os.Exit(run())
}
