// stack_adapter.c - the CAS BACnet Stack's own C++ adapter, compiled in place, in DLL mode
// =============================================================================
// This file holds no adapter code of its own. It compiles the stack's generated
// adapter straight from the submodule (adapters/cpp/, found through the -I path
// in stack.go), with CAS_BACNET_STACK_LIB_TYPE_DLL defined there too:
//
//   CASBACnetStackAdapter.cpp         LoadBACnetFunctions(): LoadLibrary/dlopen,
//                                     the API version handshake
//   CASBACnetStackAdapterDynamic.cpp  one function-pointer variable per export,
//                                     bound with GetProcAddress/dlsym (generated by
//                                     ci_scripts/generate-cpp-adapter.js)
//
// In DLL mode every BACnetStack_<Name> is a pointer variable bound at run time, so
// the executable has NO load-time dependency on the stack library: when it is
// missing, main() still runs and prints a clear message (main.go, rule 2b).
//
// They are #included from a .c file (compiled as C - both files are C-compatible)
// because cgo compiles only the files in the package's own folder, and the
// adapter is never copied into this repository.
//
// Where the library is loaded from: the adapter opens BACNET_LIB_FILE.
//   - Windows: the default, the bare name "CASBACnetStack_x64_Release.dll", which
//     LoadLibrary looks for in the executable's folder first. For the submodule
//     bin/ fallback, cgobridge_load_stack() adds that folder with SetDllDirectory.
//   - Linux: the default is "./libCASBACnetStack_x64_Release.so", relative to the
//     CURRENT directory, not the executable's - so this file defines
//     BACNET_LIB_FILE (the adapter's documented override) as the full path the
//     Go code resolved.
// =============================================================================

#include <string.h>

#if !defined(_WIN32)
static char cgobridge_stackLibraryPath[4096];
#define BACNET_LIB_FILE cgobridge_stackLibraryPath
#endif

#include "CASBACnetStackAdapter.cpp"
#include "CASBACnetStackAdapterDynamic.cpp"

#if defined(_WIN32)
#include <windows.h>
#endif

// cgobridge_load_stack opens the stack library found by the Go code in folder,
// binds every BACnetStack_* pointer and runs the version handshake. Returns false
// with CASBACnetStackAdapter_LastError() set on failure.
bool cgobridge_load_stack(const char* folder, const char* fileName)
{
#if defined(_WIN32)
    (void)fileName;
    SetDllDirectoryA(folder);
#else
    snprintf(cgobridge_stackLibraryPath, sizeof(cgobridge_stackLibraryPath), "%s/%s", folder, fileName);
#endif
    return LoadBACnetFunctions();
}
